import { expect, test } from '@playwright/test'

test('初次进入可选择四种身份，未配置正式服务时不伪装登录成功', async ({page}) => {
  await page.goto('/#/')
  await expect(page.getByRole('heading',{name:'你好，你想从哪里开始？'})).toBeVisible()
  await expect(page.getByRole('link',{name:/我是小朋友/})).toBeVisible()
  await expect(page.getByRole('link',{name:/我是志愿者/})).toBeVisible()
  await expect(page.getByRole('link',{name:/我是老师/})).toBeVisible()
  await expect(page.getByRole('link',{name:/运营人员入口/})).toBeVisible()
  await page.getByRole('link',{name:/我是小朋友/}).click()
  await expect(page).toHaveURL(/#\/login\/child/)
  await expect(page.getByRole('heading',{name:'小朋友，欢迎回来'})).toBeVisible()
  await expect(page.getByText('真实账号服务尚未连接')).toBeVisible()
  await expect(page.getByRole('button',{name:'打开我的页面'})).toBeDisabled()
})

test('独立演示中，未结对孩子可先写自我介绍并在刷新后接着写', async ({page}) => {
  await page.goto('/#/')
  await page.getByRole('link',{name:'先体验 Demo'}).click()
  await expect(page.getByText('演示设置',{exact:true})).toBeVisible()
  await page.getByText('演示设置',{exact:true}).click()
  await page.getByLabel('演示角色',{exact:true}).selectOption('child')
  await page.getByLabel('演示身份',{exact:true}).selectOption('c3')
  await page.getByText('演示设置',{exact:true}).click()
  await expect(page.getByRole('link',{name:'写一封自我介绍'})).toBeVisible()
  await page.getByRole('link',{name:'写一封自我介绍'}).click()
  await page.getByLabel('想说的话').fill('你好，我喜欢画画，也喜欢猜关于小动物的谜语。')
  await page.getByRole('button',{name:'保存草稿'}).click()
  await expect(page.getByRole('status').filter({hasText:'草稿已保存'}).first()).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('想说的话')).toHaveValue('你好，我喜欢画画，也喜欢猜关于小动物的谜语。')
  await expect(page.getByRole('button',{name:'检查并寄出'})).toBeDisabled()
})

test('演示身份不会成为正式账号，退出后回到身份选择', async ({page}) => {
  await page.goto('/#/demo')
  await expect(page.getByText('虚构身份 · 仅当前浏览器保存')).toBeVisible()
  await page.getByRole('button',{name:'退出演示'}).click()
  await expect(page.getByRole('heading',{name:'你好，你想从哪里开始？'})).toBeVisible()
  await expect(page.getByText('虚构身份 · 仅当前浏览器保存')).toHaveCount(0)
})
